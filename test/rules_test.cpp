    GB_TEST(axe, test_r_bool)
    {
        std::string x = "x", empty;

        // a function is called, also a lambda without captures, which converts to bool as a function pointer
        gbassert(!axe::parse(axe::r_bool([] { return false; }), x).matched);
        gbassert(axe::parse(axe::r_bool([] { return true; }), x).matched);
        gbassert(!axe::parse(axe::r_bool([] { return 0; }), x).matched);

        // a value or a function without arguments is evaluated also at the end of input
        gbassert(axe::parse(axe::r_bool(true), empty).matched);
        gbassert(!axe::parse(axe::r_bool(false), empty).matched);
        gbassert(axe::parse(axe::r_bool([] { return true; }), empty).matched);

        // std::ref makes a variable evaluated at parse time
        bool flag = false;
        auto flag_rule = axe::r_bool(std::ref(flag));
        gbassert(!axe::parse(flag_rule, x).matched);
        flag = true;
        gbassert(axe::parse(flag_rule, x).matched);

        // the example of the reference: the number is at the end of input
        unsigned number = 0;
        auto rule = _int >> number & axe::r_bool([&] { return number > 0 && number < 1000; });
        gbassert(axe::parse(rule, std::string("123")).matched);
        gbassert(!axe::parse(rule, std::string("1234")).matched);

        // a function of the input isn't called at the end of input, and the rule doesn't advance
        size_t calls = 0;
        auto at_x = axe::r_bool([&](auto i) { ++calls; return *i == 'x'; });
        gbassert(!axe::parse(at_x, empty).matched && calls == 0);
        auto res = axe::parse(at_x, x);
        gbassert(res.matched && res.position == x.begin() && calls == 1);
    }

    GB_TEST(axe, test_r_bin)
    {
        // a double has bytes >= 0x80, which must match also in signed char input
        double d = 1.23;
        std::string text(reinterpret_cast<const char*>(&d), sizeof d);
        gbassert(axe::parse(axe::r_bin(d) & axe::r_end(), text).matched);
        gbassert(axe::parse(axe::r_lit(1.23) & axe::r_end(), text).matched);
        gbassert(!axe::parse(axe::r_bin(2.5), text).matched);

        std::vector<unsigned char> bytes(text.begin(), text.end());
        gbassert(axe::parse(axe::r_bin(d) & axe::r_end(), bytes).matched);

        std::vector<std::byte> input(sizeof d);
        std::memcpy(input.data(), &d, sizeof d);
        gbassert(axe::parse(axe::r_bin(d) & axe::r_end(), input).matched);
        double value = 0;
        gbassert(axe::parse(axe::r_var(value), input).matched && value == d);
    }

    GB_TEST(axe, test_r_many_literals)
    {
        // r_many(literal, count) repeats the literal, r_many(literal, literal) uses the second as separator
        static_assert(std::is_same_v<decltype(axe::r_many('x', 2)), axe::r_many_t<axe::r_char<char>, axe::r_empty>>);
        gbassert(!axe::parse(axe::r_many('x', 2), std::string("x")).matched);
        gbassert(axe::parse(axe::r_many('x', 2), std::string("xx")).matched);

        std::string list = "a, a, a";
        auto res = axe::parse(axe::r_many('a', ", "), list);
        gbassert(res.matched && res.position == list.end());
    }

    GB_TEST(axe, test_r_many_empty)
    {
        // a repetition of a rule matching empty input ends instead of repeating forever
        std::string abc = "abc";
        auto res = axe::parse(*(*_d), abc);
        gbassert(res.matched && res.position == abc.begin());

        std::string digits = "12x";
        res = axe::parse(+(~_d), digits);
        gbassert(res.matched && res.position == digits.begin() + 2);

        axe::r_rule<std::string::iterator> empty_rule;
        res = axe::parse(*std::ref(empty_rule), abc);
        gbassert(res.matched && res.position == abc.begin());

        size_t calls = 0;
        res = axe::parse(*(axe::r_empty() >> [&] { ++calls; }), abc);
        gbassert(res.matched && calls == 2);

        auto tree = axe::parse_tree(*(*_d), abc);
        gbassert(tree.matched && tree.position == abc.begin() && tree.data.size() == 2);

        // the minimum number of occurrences is still counted
        std::string one = "1x";
        res = axe::parse(~_d * 3, one);
        gbassert(res.matched && res.position == one.begin() + 1);
        auto tree3 = axe::parse_tree(~_d * 3, one);
        gbassert(tree3.matched && tree3.data.size() == 3);
        auto tree2 = axe::parse_tree(axe::r_many(~_d, 2, 5), std::string("x"));
        gbassert(tree2.matched && tree2.data.size() == 2);

        // an occurrence preceded by a separator advances, even if the occurrence itself is empty
        std::string commas = ",,,";
        res = axe::parse(~_d % ',', commas);
        gbassert(res.matched && res.position == commas.end());
        auto tree4 = axe::parse_tree(~_d % ',', commas);
        gbassert(tree4.matched && tree4.position == commas.end() && tree4.data.size() == 4);
    }

    GB_TEST(axe, test_r_many_tree)
    {
        // parse_tree consumes the same input as parse: a trailing separator isn't part of the match
        std::string list = "1,2,x";
        auto rule = _d % ',';
        auto res = axe::parse(rule, list);
        auto tree = axe::parse_tree(rule, list);
        gbassert(res.matched && res.position == list.begin() + 3);
        gbassert(tree.matched && tree.position == list.begin() + 3 && tree.data.size() == 2);

        // the separator isn't evaluated after the last allowed occurrence
        size_t separators = 0;
        auto counted = axe::r_many(_d, axe::r_char(',') >> [&] { ++separators; }, 1, 2);
        std::string numbers = "1,2,3";
        res = axe::parse(counted, numbers);
        gbassert(res.matched && res.position == numbers.begin() + 3 && separators == 1);
        separators = 0;
        tree = axe::parse_tree(counted, numbers);
        gbassert(tree.matched && tree.position == numbers.begin() + 3 && separators == 1);

        // a failed separator or occurrence is reported where it failed
        auto failed = axe::parse_tree(axe::r_many(_d, ',', 3), list);
        gbassert(!failed.matched && failed.position == list.begin() + 4);
    }

    GB_TEST(axe, test_r_find_tree)
    {
        // each position is tried once, in parse_tree as in parse
        size_t evaluations = 0;
        auto x = [&](auto i1, auto i2)
        {
            ++evaluations;
            bool matched = i1 != i2 && *i1 == 'x';
            return axe::result(matched, matched ? std::next(i1) : i1);
        };
        std::string text = "abx";
        auto res = axe::parse(axe::r_find(x), text);
        gbassert(res.matched && res.position == text.end() && evaluations == 3);
        evaluations = 0;
        auto tree = axe::parse_tree(axe::r_find(x), text);
        gbassert(tree.matched && tree.position == text.end() && evaluations == 3);
    }

    GB_TEST(axe, test_unordered_and)
    {
        // A && B is A & B | B & A
        auto a = axe::r_char('a');
        auto ab = axe::r_str("ab");
        std::string aba = "aba";
        auto res = axe::parse(a && ab, aba);
        gbassert(res.matched && res.position == aba.end());

        auto b = axe::r_char('b');
        for (std::string text : { "ab", "ba" })
            gbassert(axe::parse(a && b, text).position == text.end());
        gbassert(!axe::parse(a && b, std::string("aa")).matched);

        // on failure the longest match is reported
        std::string ax = "ax";
        res = axe::parse(a && b, ax);
        gbassert(!res.matched && res.position == ax.begin() + 1);
    }

    GB_TEST(axe, test_parse_tree_rules)
    {
        // a name doesn't change the parse tree of a rule
        std::string text = "1a";
        using named_t = decltype(axe::parse_tree(axe::r_named(_d & _a, "digit and letter"), text).data);
        using plain_t = decltype(axe::parse_tree(_d & _a, text).data);
        static_assert(std::is_same_v<named_t, plain_t>);
        auto named = axe::parse_tree(axe::r_named(_d & _a, "digit and letter"), text);
        gbassert(named.matched && axe::get_as<std::string>(std::get<1>(named.data)) == "a");

        // a constrained rule without a parse tree of its own produces it_pair
        std::string id = "abc";
        auto constrained = axe::parse_tree(_ident / [](auto, auto) { return true; }, id);
        static_assert(std::is_same_v<decltype(constrained.data), axe::it_pair<std::string::iterator>>);
        gbassert(constrained.matched && constrained.position == id.end());
        gbassert(!axe::parse_tree(_ident / [](auto, auto) { return false; }, id).matched);

        // write_xml closes the optional element
        std::ostringstream os;
        std::string five = "5";
        axe::write_xml(axe::parse_tree(~_d, five).data, os);
        gbassert(os.str() == "<optional matched=\"true\">\n <![CDATA[5]]>\n</optional>\n");
    }

    GB_TEST(axe, test_extraction)
    {
        // string_view refers to the input, from any contiguous iterator
        const char* chars = "xyz";
        std::string_view view;
        gbassert(axe::parse(_ident >> view, chars, chars + 3).matched && view == "xyz");
    #if AXE_CPLUSPLUS >= 202002L
        std::string text = "abc def";
        gbassert(axe::parse(_ident >> view, text).matched && view == "abc" && view.data() == text.data());
    #endif

        // get_as of an empty range is a value-initialized object
        std::string empty;
        gbassert(axe::get_as<int>(empty.begin(), empty.end()) == 0);
    }
