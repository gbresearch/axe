// The literal operators in axe::shortcuts, which are standard C++ on every compiler: a string literal
// _axe matches the string, a character literal _axe matches the character.

#include <string>
#include <string_view>
#include "../include/axe.h"
#include <yadro/util/gbtest.h>

namespace
{
    using namespace gb::yadro::util;

    GB_TEST(axe, test_literal)
    {
        using namespace axe::shortcuts;

        std::string text = "abcd";
        auto r = axe::parse("abc"_axe, text);
        gbassert(r.matched && r.position == text.begin() + 3);
        gbassert(!axe::parse("abd"_axe, text).matched);
        gbassert(!axe::parse("abcde"_axe, text).matched); // input ends before the literal
        gbassert(axe::parse("abcd"_axe & _z, text).matched);

        // an empty literal matches without consuming input
        r = axe::parse(""_axe, text);
        gbassert(r.matched && r.position == text.begin());
        gbassert(axe::parse(""_axe & _z, std::string()).matched);

        // the characters after an embedded 0 are part of the literal
        std::string with_zero("a\0b", 3);
        gbassert(axe::parse("a\0b"_axe & _z, with_zero).matched);
        gbassert(!axe::parse("a\0c"_axe, with_zero).matched);

        // wide strings and characters
        std::wstring wtext = L"x=1";
        gbassert(axe::parse(L"x"_axe & L'='_axe & _uint & _z, wtext).matched);
        gbassert(axe::parse('x'_axe & "=1"_axe & _z, std::string_view("x=1")).matched);

        // _any and _regex
        gbassert(axe::parse(+"ab"_any & _z, std::string("abba")).matched);
        gbassert(!axe::parse("ab"_any, std::string("c")).matched);
        gbassert(axe::parse("[0-9]+"_regex & _z, std::string("123")).matched);
    }

#if AXE_CPLUSPLUS >= 202002L
    GB_TEST(axe, test_literal_utf)
    {
        using namespace axe::shortcuts;

        // with C++20 a literal of any character type is a template argument of r_strlit
        static_assert(std::is_same_v<decltype("ab"_axe), axe::r_strlit<'a', 'b'>>);
        static_assert(std::is_same_v<decltype(""_axe), axe::r_empty>);

        std::u8string u8 = u8"\u00e9t\u00e9";
        gbassert(axe::parse(u8"\u00e9t\u00e9"_axe & _z, u8).matched);
        std::u16string u16 = u"\u00e9t\u00e9";
        gbassert(axe::parse(u"\u00e9t"_axe & axe::r_char(u'\u00e9') & _z, u16).matched);
        std::u32string u32 = U"\U0001F600!";
        gbassert(axe::parse(U"\U0001F600"_axe & U"!"_axe & _z, u32).matched);
    }
#endif
}
